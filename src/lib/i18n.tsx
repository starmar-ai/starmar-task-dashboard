const dictionaries: Record<Locale, Record<Key, string>> = { id, en }

export type TFn = (key: Key, vars?: Record<string, string | number>) => string

function makeT(locale: Locale): TFn {
  return (key, vars) => {
    let s = dictionaries[locale][key] ?? key
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
    return s
  }
}

const I18nContext = createContext<{ locale: Locale; t: TFn }>({ locale: 'id', t: makeT('id') })

export function I18nProvider({ locale, children }: { locale: Locale; children: ReactNode }) {
  document.documentElement.lang = locale
  return <I18nContext.Provider value={{ locale, t: makeT(locale) }}>{children}</I18nContext.Provider>
}

export function useI18n() {
  return useContext(I18nContext)
}

/** Postgres/PostgREST errors to a sentence the user can act on. */
export function errorMessage(t: TFn, err: { message?: string; code?: string } | null | undefined): string {
  if (!err) return ''
  if (/reviewer_locked/.test(err.message ?? '')) return t('error.reviewerLocked')
  if (err.code === '42501' || /row-level security|only an admin|only the reviewer/i.test(err.message ?? '')) return t('error.permission')
  if (/at least one admin/i.test(err.message ?? '')) return t('settings.lastAdmin')
  const msg = err.message ?? ''
  if (msg.includes('no_change')) return t('error.crNoChange')
  if (msg.includes('duplicate_request')) return t('error.crDuplicate')
  if (msg.includes('reason_required')) return t('error.crReason')
  if (msg.includes('value_invalid')) return t('error.crValueInvalid')
  if (msg.includes('value_required')) return t('error.crValueRequired')
  if (msg.includes('edit_directly')) return t('error.crEditDirectly')
  if (msg.includes('already_decided')) return t('error.crDecided')
  if (msg.includes('note_required')) return t('error.crNote')
  if (msg.includes('task_not_found')) return t('error.crTaskGone')
  if (msg.includes('tasks_start_before_deadline')) return t('error.crDeadlineOrder')
  if (msg.includes('person_not_in_project')) return t('error.personNotInProject')
  if (msg.includes('reviewer_locked')) return t('error.reviewerLocked')
  if (msg.includes('task_blocked')) return t('error.taskBlocked')
  if (msg.includes('needs_review')) return t('error.needsReview')
  if (msg.includes('dependency_cycle')) return t('error.dependencyCycle')
  if (msg.includes('review_note_required')) return t('error.reviewNoteRequired')
  if (msg.includes('task_not_in_review')) return t('error.notInReview')
  return t('error.generic', { message: err.message ?? 'unknown' })
}
